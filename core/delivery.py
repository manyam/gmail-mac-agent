import os
import subprocess
from datetime import datetime
from pathlib import Path
from typing import Optional


class DeliveryManager:
    """Manages writing Daily Briefs to Markdown and triggering macOS system notifications."""

    def __init__(self, output_dir: Path, notification_enabled: bool = True, sound: str = "Glass"):
        self.output_dir = Path(output_dir)
        self.notification_enabled = notification_enabled
        self.sound = sound

    def save_brief(self, brief_content: str, provider_meta: str) -> Path:
        """Saves daily brief markdown file to the designated directory."""
        self.output_dir.mkdir(parents=True, exist_ok=True)

        date_slug = datetime.now().strftime("%Y-%m-%d")
        file_path = self.output_dir / f"Daily_Brief_{date_slug}.md"

        # If a file already exists today, append a run timestamp
        if file_path.exists():
            time_slug = datetime.now().strftime("%H%M")
            file_path = self.output_dir / f"Daily_Brief_{date_slug}_{time_slug}.md"

        full_content = (
            f"{brief_content}\n\n"
            f"---\n"
            f"*Generated by {provider_meta} on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*\n"
        )

        with open(file_path, "w", encoding="utf-8") as f:
            f.write(full_content)

        print(f"[SUCCESS] Daily Brief saved to: {file_path}")
        return file_path

    def notify_macos(self, message: str, title: str = "Gmail Daily Brief") -> None:
        """Sends native macOS notification banner via osascript."""
        if not self.notification_enabled:
            return

        try:
            # Escape double quotes for AppleScript
            safe_msg = message.replace('"', '\\"')
            safe_title = title.replace('"', '\\"')
            script = f'display notification "{safe_msg}" with title "{safe_title}"'
            if self.sound:
                script += f' sound name "{self.sound}"'

            subprocess.run(
                ["osascript", "-e", script],
                check=False,
                capture_output=True,
                text=True,
            )
        except Exception as e:
            print(f"[DEBUG] Could not send macOS notification: {e}")
