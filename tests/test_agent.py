import base64
import os
import shutil
import tempfile
import unittest
from pathlib import Path

from core.delivery import DeliveryManager
from core.parser import EmailParser, ParsedEmailThread
from core.prompts import build_daily_brief_prompt
from core.state import StateManager


class TestGmailAgent(unittest.TestCase):
    def setUp(self):
        self.test_dir = tempfile.mkdtemp()

    def tearDown(self):
        shutil.rmtree(self.test_dir)

    def test_parser_mime_and_quotes(self):
        # Simulated raw Gmail API message
        body_text = (
            "Hi Alice,\n\n"
            "Can you please review the Q3 budget proposal by 3 PM today?\n\n"
            "On Mon, Oct 10, 2026 at 9:00 AM Bob <bob@example.com> wrote:\n"
            "> Here is the old thread that should be stripped."
        )
        b64_body = base64.urlsafe_b64encode(body_text.encode("utf-8")).decode("ASCII")

        raw_thread = {
            "id": "18a1b2c3d4e5f600",
            "messages": [
                {
                    "id": "msg_001",
                    "snippet": "Can you please review the Q3 budget proposal",
                    "payload": {
                        "headers": [
                            {"name": "Subject", "value": "Urgent: Q3 Budget Proposal Review"},
                            {"name": "From", "value": "Bob Smith <bob@example.com>"},
                            {"name": "To", "value": "Alice <alice@example.com>"},
                            {"name": "Date", "value": "Tue, 11 Oct 2026 10:00:00 -0700"},
                        ],
                        "mimeType": "text/plain",
                        "body": {"data": b64_body},
                    },
                }
            ],
        }

        parsed = EmailParser.parse_thread(raw_thread)
        self.assertEqual(parsed.thread_id, "18a1b2c3d4e5f600")
        self.assertEqual(parsed.subject, "Urgent: Q3 Budget Proposal Review")
        self.assertEqual(parsed.participants, ["Bob Smith <bob@example.com>"])
        self.assertIn("18a1b2c3d4e5f600", parsed.web_link)

        # Quoted text after 'On Mon, ... wrote:' should be removed
        self.assertNotIn("Here is the old thread that should be stripped", parsed.messages[0].body_text)
        self.assertIn("Can you please review the Q3 budget proposal by 3 PM today?", parsed.messages[0].body_text)

    def test_state_manager_deduplication(self):
        db_path = Path(self.test_dir) / "state.db"
        state_mgr = StateManager(db_path)

        # Thread 1: not processed yet
        self.assertFalse(state_mgr.is_processed("thread_1", "hist_1", 2))

        # Mark processed
        state_mgr.mark_processed("thread_1", "hist_1", 2)
        self.assertTrue(state_mgr.is_processed("thread_1", "hist_1", 2))

        # If a new reply arrives (message_count increases to 3)
        self.assertFalse(state_mgr.is_processed("thread_1", "hist_1", 3))

    def test_delivery_markdown_saving(self):
        output_dir = Path(self.test_dir) / "briefs"
        delivery_mgr = DeliveryManager(output_dir, notification_enabled=False)

        brief_text = "# Daily Brief\n- Action items listed here."
        saved_file = delivery_mgr.save_brief(brief_text, "Local Ollama (llama3.2)")

        self.assertTrue(saved_file.exists())
        content = saved_file.read_text(encoding="utf-8")
        self.assertIn("Daily Brief", content)
        self.assertIn("Action items listed here.", content)
        self.assertIn("Local Ollama", content)

    def test_prompt_builder(self):
        thread = ParsedEmailThread(
            thread_id="thread_xyz",
            subject="Contract Approval Required",
            participants=["Legal Team <legal@corp.com>"],
            latest_date="11 Oct 2026",
            web_link="https://mail.google.com/mail/u/0/#all/thread_xyz",
            messages=[],
        )
        prompt = build_daily_brief_prompt([thread])
        self.assertIn("Contract Approval Required", prompt)
        self.assertIn("thread_xyz", prompt)
        self.assertIn("Action Required", prompt)

    def test_llm_fallback(self):
        from unittest.mock import MagicMock
        from core.config import LLMConfig
        from core.llm_client import LLMClient

        primary = LLMConfig(provider="ollama", model="llama3.2")
        backup = LLMConfig(provider="gemini", model="gemini-3.8-flash")
        client = LLMClient(primary, backup)

        # Mock Ollama failing and Gemini succeeding
        client._call_ollama = MagicMock(side_effect=RuntimeError("Connection refused"))
        client._call_gemini = MagicMock(return_value="Generated by Gemini Flash")

        result, provider_meta = client.generate("test prompt")
        self.assertEqual(result, "Generated by Gemini Flash")
        self.assertIn("Fallback", provider_meta)
        client._call_ollama.assert_called_once()
        client._call_gemini.assert_called_once()

    def test_delivery_label_subdirectories(self):
        output_dir = Path(self.test_dir) / "briefs"
        delivery_mgr = DeliveryManager(output_dir, notification_enabled=False)

        brief_text = "# Daily Brief\n- Test label brief content."
        saved_file = delivery_mgr.save_brief(brief_text, "Ollama", label="INBOX")

        self.assertTrue(saved_file.exists())
        self.assertEqual(saved_file.parent.name, "INBOX")
        self.assertEqual(saved_file.parent.parent, output_dir)
        self.assertIn("Daily_Brief_", saved_file.name)

        # Test another label
        saved_work = delivery_mgr.save_brief(brief_text, "Ollama", label="Work")
        self.assertTrue(saved_work.exists())
        self.assertEqual(saved_work.parent.name, "Work")

    def test_state_manager_label_scoping(self):
        db_path = Path(self.test_dir) / "state.db"
        state_mgr = StateManager(db_path)

        # Mark thread_1 processed for INBOX only
        state_mgr.mark_processed("thread_1", "hist_1", 2, label="INBOX")

        # Should be processed for INBOX
        self.assertTrue(state_mgr.is_processed("thread_1", "hist_1", 2, label="INBOX"))
        # Should NOT be processed for Work
        self.assertFalse(state_mgr.is_processed("thread_1", "hist_1", 2, label="Work"))

        # Filter unseen threads check
        meta = [{"id": "thread_1", "historyId": "hist_1"}]
        self.assertEqual(len(state_mgr.filter_unseen_threads(meta, label="INBOX")), 0)
        self.assertEqual(len(state_mgr.filter_unseen_threads(meta, label="Work")), 1)

    def test_prompt_builder_with_label(self):
        thread = ParsedEmailThread(
            thread_id="thread_xyz",
            subject="Invoice Received",
            participants=["Billing <billing@corp.com>"],
            latest_date="12 Oct 2026",
            web_link="https://mail.google.com/mail/u/0/#all/thread_xyz",
            messages=[],
        )
        prompt = build_daily_brief_prompt([thread], label="Finance")
        self.assertIn("Daily Brief [Finance]", prompt)
        self.assertIn("Label: Finance", prompt)


if __name__ == "__main__":
    unittest.main()
